export const DICTIONARIES: Record<Locale, Record<string, string>> = {
  en,
  hi,
  // Phase 4: the remaining launch languages register here (registry ready,
  // PRD §11) and resolve through the English fallback chain until their
  // community/AI catalogs land (Phase 7 of the Cycle-2 roadmap).
  bn: {}, te: {}, mr: {}, ta: {}, gu: {}, kn: {}, ml: {}, or: {},
  pa: {}, as: {}, ur: {}, mai: {}, sd: {},
}

export type TFunction = (key: keyof typeof en, params?: Record<string, string>) => string

/** Server-side t() for server components (async request params, Next 16). */
export function t(locale: Locale, key: keyof typeof en, params?: Record<string, string>): string {
  let text: string = DICTIONARIES[locale][key] ?? en[key]
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, value)
    }
  }
  return text
}